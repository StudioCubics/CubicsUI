import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = join(dirname(fileURLToPath(import.meta.url)), "src");
const groups = ["Brand", "Static", "Animated"];

const entries = groups
  .flatMap((group) =>
    readdirSync(join(src, group), { withFileTypes: true })
      // Flat files (Static/Brand) or folders (Animated/<Name>/<Name>.tsx)
      .filter((d) =>
        d.isDirectory()
          ? !d.name.startsWith("_")
          : d.name.endsWith(".tsx") && !d.name.startsWith("_"),
      )
      .map((d) => {
        const name = d.isDirectory() ? d.name : d.name.replace(/\.tsx$/, "");
        // Folder icons are imported from "./Group/Name/Name"
        const path = d.isDirectory() ? `${group}/${name}/${name}` : `${group}/${name}`;
        // BrushIcon -> ["BrushIcon", "Brush"]; CubicsUIFavicon -> ["CubicsUIFavicon"]
        const short = name.replace(/Icon$/, "");
        const keys = short !== name ? [name, short] : [name];
        return { group, name, path, keys };
      }),
  )
  .sort((a, b) => a.name.localeCompare(b.name));

// Fail on key collisions (e.g. a file named "Brush.tsx" next to "BrushIcon.tsx")
const allKeys = entries.flatMap((e) => e.keys);
const dupes = allKeys.filter((k, i) => allKeys.indexOf(k) !== i);
if (dupes.length) throw new Error(`Duplicate icon keys: ${dupes.join(", ")}`);

const imports = entries
  .map((e) => `import { ${e.name} } from "./${e.path}";`)
  .join("\n");

// Explicit type is required because of isolatedDeclarations
const type = entries
  .flatMap((e) => e.keys.map((k) => `  ${k}: typeof ${e.name};`))
  .join("\n");

const values = entries
  .flatMap((e) =>
    e.keys.map((k) => (k === e.name ? `  ${k},` : `  ${k}: ${e.name},`)),
  )
  .join("\n");

writeFileSync(
  join(src, "registry.ts"),
  `// AUTO-GENERATED by ../generateRegistry.mjs. Do not edit.
${imports}

export const icons: {
${type}
} = {
${values}
};

export type IconName = keyof typeof icons;
`,
);

console.log(
  `Generated registry with ${allKeys.length} keys for ${entries.length} icons`,
);