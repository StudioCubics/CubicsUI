/** Reverse of `LANGUAGE_IDENTIFIER_TO_EXTENSION`.
 Since multiple identifiers can map to the same extension (e.g. "ts"/"typescript" -> ".ts"),
 the first identifier encountered for a given extension wins.
  */
export const EXTENSION_TO_LANGUAGE_IDENTIFIER: Record<string, string> =
  Object.entries(LANGUAGE_IDENTIFIER_TO_EXTENSION).reduce(
    (acc, [identifier, extension]) => {
      if (extension && !(extension in acc)) {
        acc[extension] = identifier;
      }
      return acc;
    },
    {} as Record<string, string>,
  );
